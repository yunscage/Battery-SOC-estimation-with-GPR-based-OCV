function Para=ECM_Para(x,Tem,argv,curr)
switch argv
    case 'R0'
        Para=ECM_R0(x,Tem);
    case 'B1'
        Para=ECM_B1(x,Tem);
    case 'B2'
        Para=ECM_B2(x,Tem);
    case 'A1'
        Para=ECM_A1(x,Tem);
    case 'A2'
        Para=ECM_A2(x,Tem);
    case 'Cap'
        Para=Capacity(Tem);
    otherwise
        disp('Chose R0 B1 B2 Tau1 Tau2!');
end
end

